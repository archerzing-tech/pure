// 截断卫生（注入面）——与渲染侧 0b5679f 同族问题的另一半。
// 截断/摘录出来的文本可能停在 ``` 围栏中途（压缩摘要对消息的 head/tail 截、
// rehydrate 对文件内容的 cap 截、记忆条目写入时的长度截）。未闭合围栏注入
// 提示词后，会把围栏之后的**整段提示词**吞进代码块里读——渲染侧的表现是
// 错误卡，注入侧的表现是模型把后续指令当代码，且从不报错、最难察觉。
// 修法选「补收栏」而不是「截掉半截围栏」：注入的是历史/文件的真实内容，
// 截掉的围栏段本身是真信息，丢弃=记忆失真；补一个收栏后内容无损、结构
// 闭合，危害即除。围栏口径与渲染链一致：行首 ≤3 空格的 ``` 分隔行。

/** 围栏分隔行：行首 ≤3 空格的 ``` 行。开栏可带信息串（```ts / ```map），
 *  收栏是裸 ```——两者都计入奇偶（漏计开栏会把「开了没收」误判成闭合）。
 *  行中出现的 ``` 不是分隔行，与渲染器口径一致。 */
const FENCE_LINE_RE = /^[ \t]{0,3}```/gm;
const CLOSING_FENCE = '```';

/**
 * 若文本含未闭合的 ``` 围栏（分隔行计数为奇数），末尾补一个收栏；否则原样
 * 返回。只看分隔行奇偶——与模型/渲染器对围栏的理解一致，不做语义解析。
 */
export function closeDanglingFence(text: string): string {
  const count = (text.match(FENCE_LINE_RE) ?? []).length;
  if (count % 2 === 0) return text;
  return text.endsWith('\n') ? `${text}${CLOSING_FENCE}` : `${text}\n${CLOSING_FENCE}`;
}
